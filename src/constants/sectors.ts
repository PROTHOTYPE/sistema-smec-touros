export const resolveCanonicalSectorId = (sectorIdOrCode?: string): Sector['id'] => {
  if (!sectorIdOrCode) return 'pedagogico';
  if (sectorIdOrCode === 'TI-SMEC') return 'suporte_ti';
  const matched = SECTORS.find(
    s =>
      s.id.toLowerCase() === sectorIdOrCode.toLowerCase() ||
      s.code.toLowerCase() === sectorIdOrCode.toLowerCase()
  );
  return matched ? matched.id : 'pedagogico';
};
